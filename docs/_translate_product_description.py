def paragraph_text(p) -> str:
    return "".join(t.text or "" for t in p.iter(qn("w:t"))) + "".join(
        "\t" for _ in p.iter(qn("w:tab"))
    )


def _run_with_text(text: str, *, hyperlink_style: bool = False):
    run = OxmlElement("w:r")
    if hyperlink_style:
        rpr = OxmlElement("w:rPr")
        rstyle = OxmlElement("w:rStyle")
        rstyle.set(qn("w:val"), "Hyperlink")
        rpr.append(rstyle)
        run.append(rpr)
    t = OxmlElement("w:t")
    if text.startswith(" ") or text.endswith(" "):
        t.set(qn("xml:space"), "preserve")
    t.text = text
    run.append(t)
    return run


def _replace_field_prefix(p, text: str, field_name: str, hyperlink: bool = False):
    container = None
    for elem in p.iter(qn("w:hyperlink") if hyperlink else qn("w:p")):
        if any(field_name in (i.text or "") for i in elem.iter(qn("w:instrText"))):
            container = elem
            break
    if container is None:
        return False
    children = list(container)
    instr_index = next(
        i for i, child in enumerate(children)
        if any(field_name in (instr.text or "") for instr in child.iter(qn("w:instrText")))
    )
    start = instr_index - 1
    while start > 0 and not any(
        fc.get(qn("w:fldCharType")) == "begin" for fc in children[start].iter(qn("w:fldChar"))
    ):
        start -= 1
    prefix = children[:start]
    keep_tab = next(
        (child for child in reversed(prefix) if list(child.iter(qn("w:tab")))), None
    )
    for child in children:
        container.remove(child)
    container.append(_run_with_text(text, hyperlink_style=hyperlink))
    if keep_tab is not None:
        tab_run = OxmlElement("w:r")
        tab_run.append(OxmlElement("w:tab"))
        container.append(tab_run)
    for child in children[start:]:
        container.append(child)
    return True


def replace_paragraph(p, text: str):
    if _replace_field_prefix(p, text, "PAGEREF", hyperlink=True):
        return
    if _replace_field_prefix(p, text, "PAGE"):
        return
    nodes = list(p.iter(qn("w:t")))
    if not nodes:
        run = OxmlElement("w:r")
        t = OxmlElement("w:t")
        t.text = text
        run.append(t)
        p.append(run)
        return
    nodes[0].text = text
    if text.startswith(" ") or text.endswith(" "):
        nodes[0].set(qn("xml:space"), "preserve")
    for node in nodes[1:]:
        node.text = ""


def set_cell(cell, text: str):
    paras = cell.paragraphs
    if not paras:
        cell.add_paragraph()
        paras = cell.paragraphs
    replace_paragraph(paras[0]._p, text)
    for p in paras[1:]:
        for t in p._p.iter(qn("w:t")):
            t.text = ""


